"""Regenerate docs/engine-questions.md from the code, so the list can never drift from what the engine does."""
import os, sys, glob, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from engine.query import SWISS_COUNT, CUBI, IFC_COUNT_WORD, SYN, DEFINITIONS
from engine.nlq import CATEGORY, INTENT, SWISS_LABELS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["# Engine question types (generated by tools/gen_engine_questions.py, do not edit by hand)", "",
       "Every question type below is answered from geometry or a trained detector, with evidence. "
       "`query(path, intent, category, scope)` builds the canonical question; `answer(path, any_question)` also accepts free-form "
       "questions in en/zh/fi/sv/de/fr/it via `engine/nlq.py` and returns `method: unrecognised_question` instead of guessing.", ""]
out += ["## swiss_dwellings (vector plans, one storey)", "", "| intent | category | scope | canonical question |", "|---|---|---|---|"]
for k, q in SWISS_COUNT.items(): out.append(f"| count | {k} | whole floor | {q} |")
out += ["| count | room | {label} | How many rooms labelled '<label>' are there on this floor? |",
        "| area | — | {room: number} | What is the net floor area of room <number> ('<label>') in m²? |",
        "| area | — | {apartment: letter} | What is the net floor area of apartment <A> in m², summing all its rooms except balconies, loggias, terraces and other outdoor spaces? |",
        "| area | — | {label} | What is the total net area in m² of all rooms labelled '<label>' on this floor? |",
        "| area | — | whole floor | What is the total net floor area in m² of all numbered indoor rooms on this floor (excluding balconies, loggias, terraces and other outdoor spaces, shafts and voids)? |", ""]
out += ["## ifc_models / ifc_bench (IFC building models)", "", "| intent | category | scope | canonical question |", "|---|---|---|---|"]
for k, w in IFC_COUNT_WORD.items():
    out.append(f"| count | {k} | whole model | How many {w} are there in the model '<model name>'? |")
    out.append(f"| count | {k} | {{storey}} | How many {w} are shown on the floor plan of '<storey>'? |")
out += ["| area | room | {room, storey} | What is the net floor area of the room '<Name (Number)>' on '<storey>', in m²? |",
        "| area | room | {storey} | What is the total net floor area of all rooms (spaces) on '<storey>', in m²? |",
        "| length / area / volume | wall | {storey} | total length (m) / net side area (m²) / net volume (m³) of all walls on '<storey>' |",
        "| volume | slab | {storey} | What is the total net volume of all slabs on '<storey>', in m³? |", ""]
out += ["## cubicasa5k (raster plans, counts only)", "", "| category | canonical question |", "|---|---|"]
for k, q in CUBI.items(): out.append(f"| {k} | {q} |")
out += ["", "## method strings", "", "| method | meaning |", "|---|---|"]
meth = set()
for f in glob.glob(os.path.join(ROOT, "eval", "results", "score_*.txt")):
    meth |= {re.sub(r"\[[^\]]*\]", "[…]", m) for m in re.findall(r"^\S+\s+(\S+)\s+\d+/\d+", open(f).read(), re.M)}
for m in sorted(meth): out.append(f"| `{m}` | {m.split(':')[0]} solver, question type `{m.split(':')[-1]}` |")
out += ["| `query:unsupported` | valid question, but this combination is not supported for this drawing (reason in warnings) |",
        "| `unrecognised_question` | free-form question could not be mapped; warnings list the supported types |", ""]
out += ["## free-form vocabulary (engine/nlq.py)", "", "| category | words recognised |", "|---|---|"]
for k, ws in CATEGORY.items(): out.append(f"| {k} | {', '.join(ws)} |")
out += ["", "| intent | pattern |", "|---|---|"] + [f"| {n} | `{p.replace('|', ' / ')}` |" for n, p in INTENT]
out += ["", "Room types on Swiss plans map to the labels written in the drawing: " +
        "; ".join(f"{k} → {', '.join(v)}" for k, v in SWISS_LABELS.items()), "",
        "## definitions", ""] + [f"- **{k}**: {v}" for k, v in DEFINITIONS.items()]
open(os.path.join(ROOT, "docs", "engine-questions.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote docs/engine-questions.md,", len(out), "lines")
